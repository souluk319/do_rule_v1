function shuffle<T>(arr: T[]): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

const POOL: Record<number, string[]> = {
  4: WORDS_4,
  5: WORDS_5,
  6: WORDS_6,
};

/**
 * 사용하지 않은 단어 중에서 랜덤으로 하나 반환합니다.
 * 모두 사용했으면 처음부터 다시 순환합니다.
 */
export function generateNaturalFallback(charLen: number, usedPrompts: Set<string>): string {
  const pool = POOL[charLen] ?? POOL[4];

  // 글자 수가 정확히 맞는 단어만 (방어적 필터)
  const valid = pool.filter(w => w.length === charLen);
  const available = valid.filter(w => !usedPrompts.has(w));

  if (available.length > 0) {
    return available[Math.floor(Math.random() * available.length)];
  }

  // 전부 사용했으면 셔플 후 재순환
  const recycled = shuffle(valid);
  return recycled[0] ?? '도레미파';
}

/**
 * 특정 글자 수의 전체 단어 풀을 셔플하여 반환합니다.
 * OllamaService의 폴백(Plan C)에서 사용합니다.
 */
export function getFallbackPool(charLen: number): string[] {
  const pool = POOL[charLen] ?? POOL[4];
  return shuffle(pool.filter(w => w.length === charLen));
}
